import asyncio
from playwright.async_api import async_playwright
U='file:///workspace/akno-app/index.html'
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch()
    pg=await b.new_page(viewport={'width':430,'height':932},device_scale_factor=3,has_touch=False)
    errs=[];pg.on('pageerror',lambda e:errs.append(str(e)));pg.on('console',lambda m:m.type=='error' and errs.append(m.text))
    await pg.goto(U);await pg.evaluate('localStorage.clear()');await pg.reload();await pg.wait_for_timeout(600)
    S=lambda n:pg.screenshot(path=f'shots/{n}.png')
    await S('01-resume')
    print('badge',await pg.inner_text('.bdg'))
    await pg.click('text=Appels >> nth=-1');await pg.wait_for_timeout(500);await S('02-appels')
    await pg.fill('#q','lyon');await pg.wait_for_timeout(200);await S('03-recherche');print('pills',await pg.inner_text('#pills'))
    await pg.fill('#q','');await pg.click('[data-f=urgent]');await S('04-urgents');await pg.click('[data-f=tous]')
    fg=pg.locator('.sw[data-id="2"] .fg');bb=await fg.bounding_box()
    await pg.mouse.move(bb['x']+300,bb['y']+40);await pg.mouse.down();await pg.mouse.move(bb['x']+150,bb['y']+42,steps=8);await pg.mouse.up();await pg.wait_for_timeout(400);await S('05-swipe')
    await pg.click('.sw[data-id="2"] [data-act=note]');await pg.wait_for_timeout(400);await pg.fill('#snote','Rappeler après 18h');await S('06-note-sheet')
    await pg.click('[data-act=savenote]');await pg.wait_for_timeout(300)
    await pg.click('.sw[data-id="2"] .qk');await pg.wait_for_timeout(300);await S('07-rappele-toast')
    await pg.click('.sw[data-id="1"] .fg');await pg.wait_for_timeout(500);await S('08-detail')
    print('badge after',await pg.locator('.bdg').all_inner_texts())
    await pg.fill('#ntxt','Prévoir mesure du ballon existant + photos');await pg.click('[data-st=rdv_pris]');await pg.wait_for_timeout(300);await S('09-detail-statut')
    await pg.click('[data-act=back]');await pg.wait_for_timeout(400);print('hash',await pg.evaluate('location.hash'))
    await pg.click('.tbb[aria-label=Agenda]');await pg.wait_for_timeout(500);await S('10-agenda')
    await pg.click('[data-act=wnext]');await pg.wait_for_timeout(300);await S('11-agenda-semaine')
    await pg.click('[data-act=today]');await pg.wait_for_timeout(300)
    if await pg.locator('.blk').count():
      await pg.locator('.blk').first.click();await pg.wait_for_timeout(300);print('blk->',await pg.evaluate('location.hash'));await pg.go_back()
    await pg.click('.tbb[aria-label=Clients]');await pg.wait_for_timeout(500);await S('12-clients')
    await pg.locator('.lrow').first.click();await pg.wait_for_timeout(400);await S('13-fiche-client')
    await pg.click('.tbb[aria-label=Réglages]');await pg.wait_for_timeout(500);await S('14-reglages')
    await pg.click('[data-tg=resume]');await pg.click('[data-act=reset]');await pg.wait_for_timeout(300);await S('15-reset')
    await pg.reload();await pg.wait_for_timeout(300)
    await pg.click('.tbb[aria-label=Résumé]');await pg.wait_for_timeout(400);await S('16-resume2')
    d=await b.new_page(viewport={'width':1440,'height':960});await d.goto(U);await d.wait_for_timeout(500);await d.screenshot(path='shots/17-desktop.png')
    print('errors',errs)
    await b.close()
asyncio.run(main())

from playwright.sync_api import sync_playwright
U='file:///workspace/akno-app/index.html'
errs=[]
def chk(pg,tag):
    ov=pg.evaluate("document.documentElement.scrollWidth>innerWidth+1")
    if ov: errs.append('overflow '+tag)
with sync_playwright() as p:
    b=p.chromium.launch(args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
    for W,H,tag in [(390,844,'m'),(1024,768,'t'),(1440,900,'d')]:
        ctx=b.new_context(viewport={'width':W,'height':H},device_scale_factor=2 if tag!='m' else 3)
        pg=ctx.new_page()
        pg.on('console',lambda m,t=tag:errs.append(t+' console '+m.text) if m.type=='error' else None)
        pg.on('pageerror',lambda e,t=tag:errs.append(t+' pageerror '+str(e)))
        pg.goto(U);pg.evaluate("localStorage.clear()");pg.goto(U+'#/');pg.wait_for_timeout(1200)
        def shot(n):
            chk(pg,tag+n)
            if tag!='t' or n in('dashboard','appels'): pg.screenshot(path=f'shots/v5-{ {"m":"mobile","t":"tablet","d":"desktop"}[tag]}-{n}.png')
        shot('dashboard')
        pg.goto(U+'#/appels');pg.wait_for_timeout(400);shot('appels')
        pg.click('[data-f=ar]');pg.wait_for_timeout(200)
        n1=pg.evaluate("document.querySelectorAll('.r').length")
        pg.click('[data-f=tous]')
        pg.goto(U+'#/appel/2');pg.wait_for_timeout(400);shot('detail')
        pg.click('[data-st=rappele]');pg.wait_for_timeout(200)
        st=pg.evaluate("JSON.parse(localStorage.akno_demo_v5).calls.find(c=>c.id==2).statut")
        pg.fill('#note','Rappeler après 17 h');pg.dispatch_event('#note','change')
        pg.click('[data-f=ar]') if tag!='m' else pg.goto(U+'#/appels') ; pg.wait_for_timeout(200)
        pg.goto(U+'#/agenda');pg.wait_for_timeout(400);shot('agenda')
        pg.click('[data-view=semaine]');pg.wait_for_timeout(200);shot('agenda-semaine')
        pg.click('[data-view=mois]');pg.wait_for_timeout(200);shot('agenda-mois')
        pg.click('[data-view=jour]');pg.click('[data-wk="1"]');pg.click('[data-wk="-1"]')
        nb=pg.evaluate("JSON.parse(localStorage.akno_demo_v5).rdvs.length")
        pg.click('.fab' if tag=='m' else 'button.btns.dsk');pg.wait_for_timeout(400);shot('rdv-new')
        pg.fill('[name=nom]','Test Client');pg.fill('[name=tel]','06 00 00 00 01');pg.click('[data-type=Installation]')
        pg.fill('[name=adr]','1 rue Test, 69001 Lyon');pg.click('.sh .ok');pg.wait_for_timeout(300)
        na=pg.evaluate("JSON.parse(localStorage.akno_demo_v5).rdvs.length")
        rid=pg.evaluate("JSON.parse(localStorage.akno_demo_v5).rdvs.find(r=>r.nom_client=='Test Client').id")
        pg.goto(U+'#/rdv/'+rid);pg.wait_for_timeout(300);shot('rdv-detail')
        pg.click('[data-act=editrdv]');pg.wait_for_timeout(300);pg.fill('[name=nom]','Test Modifié');pg.click('.sh .ok');pg.wait_for_timeout(300)
        ed=pg.evaluate(f"JSON.parse(localStorage.akno_demo_v5).rdvs.find(r=>r.id=='{rid}').nom_client")
        pg.click('[data-act=delrdv]');pg.wait_for_timeout(200);shot('rdv-delete');pg.click('[data-act=dodel]');pg.wait_for_timeout(300)
        nd=pg.evaluate("JSON.parse(localStorage.akno_demo_v5).rdvs.length")
        pg.goto(U+'#/assistant');pg.wait_for_timeout(400);shot('assistant')
        pg.click('[data-ask]');pg.wait_for_timeout(300)
        for q in ['Résume ma semaine','Quels devis relancer ?','Quels RDV demain ?','Quelle météo ?']:
            pg.fill('#askq',q);pg.press('#askq','Enter');pg.wait_for_timeout(150)
        pg.evaluate("scrollTo(0,0)");pg.wait_for_timeout(100)
        nch=pg.evaluate("JSON.parse(localStorage.akno_demo_v5).chat.length")
        pg.goto(U+'#/assistant');pg.wait_for_timeout(300)
        pg.evaluate("document.querySelector('.ub')&&document.querySelector('.ub').scrollIntoView()");pg.wait_for_timeout(200);shot('assistant-chat')
        pg.goto(U+'#/reglages');pg.wait_for_timeout(300);shot('reglages')
        print(tag,'ar rows',n1,'status',st,'rdv',nb,'->',na,'edit',ed,'del->',nd,'chat',nch)
        ctx.close()
print('ERRORS',errs)
